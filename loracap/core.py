#!/usr/bin/env python3
"""
loracap.core
=====================

Site-independent LoRa network-capacity simulation engine.

This module implements the collision physics of LoRaSim (Bor, Roedig, Voigt,
Alonso, "Do LoRa Low-Power Wide-Area Networks Scale?", MSWiM 2016,
https://github.com/mcbor/lorasim), re-implemented in Python 3 (the original is
Python 2) and extended in three respects:

  - multiple orthogonal uplink channels are simulated directly, so capacity is
    obtained for the whole network instead of being extrapolated from a
    single-channel result;
  - the receiver's chip-wide simultaneous-demodulation limit is enforced. The
    limit exists in the original loraDir.py as `maxBSReceives` but is only
    counted there, never applied to the reported DER;
  - nodes can be placed inside an arbitrary polygon (a real deployment
    boundary) instead of only inside a theoretical coverage disc.

Collision model, unchanged from the original:
  - two packets can collide only if they share BOTH the same channel and the
    same spreading factor, since LoRa spreading factors are quasi-orthogonal;
  - a newly arrived packet whose critical preamble section clears an in-flight
    packet is "saved by the preamble" and no collision is registered;
  - otherwise the capture effect applies: the stronger packet survives if the
    RSSI difference reaches `capture_threshold_db`, otherwise both are lost;
  - independently, a packet is lost if its RSSI is below the receiver
    sensitivity for its spreading factor.

This module contains NO site-specific or project-specific constants. Every
physical parameter arrives through a `SimConfig`. Do not edit this file to
change a parameter: edit the study that builds the config.
"""
from __future__ import annotations

import math
import random
import statistics as stats
from dataclasses import dataclass
from typing import Dict, Optional, Sequence, Tuple


@dataclass(frozen=True)
class SimConfig:
    """Everything the engine needs to run. Built by `loracap.study`
    from a study definition, not written by hand."""

    # --- radio / link parameters ---
    payload_bytes: int
    coding_rate: int                        # CR index; airtime uses 4/(4+coding_rate)
    tx_power_dbm: float
    net_antenna_gain_db: float              # Gtx + Grx - cable/connector losses

    # --- propagation: L(d) = path_loss_ref_db + 10*gamma*log10(d/d0) ---
    path_loss_exponent: float               # gamma
    path_loss_ref_db: float                 # path loss [dB] at d0
    path_loss_ref_distance_m: float         # d0 [m]
    min_valid_distance_m: float             # lower bound of the fit's validity range

    # --- receiver sensitivity per spreading factor [dBm], at bw_khz ---
    sensitivity_dbm: Dict[int, float]
    bw_khz: int

    # --- gateway / channel parameters ---
    n_channels: int
    max_simultaneous_demodulations: Optional[int]

    # --- traffic ---
    avg_send_interval_ms: float
    capture_threshold_db: float = 6.0

    # --- spatial node placement ---
    # 'disc'    : uniformly at random inside the coverage disc implied by the
    #             link budget. The classic LoRaSim assumption. Answers "what can
    #             this gateway support in the abstract?".
    # 'polygon' : uniformly at random inside `placement_polygons_m`, gateway at
    #             the origin. Answers "what does THIS deployment support?".
    placement: str = "disc"
    placement_polygons_m: Optional[Sequence[Sequence[Tuple[float, float]]]] = None

    # Spreading factors an adaptive ("MULTI") scenario may select from. When
    # None, every SF present in `sensitivity_dbm` is allowed.
    adaptive_sf_options: Optional[Sequence[int]] = None


# ---------------------------------------------------------------------------
# Link-level physics
# ---------------------------------------------------------------------------

def airtime_ms(cfg: SimConfig, sf: int) -> float:
    """LoRa time-on-air in ms (standard formula, LoRa Design Guide)."""
    bw_khz = cfg.bw_khz
    de = 1 if (bw_khz == 125 and sf in (11, 12)) else 0
    n_pream = 8
    t_sym = (2.0 ** sf) / bw_khz
    t_pream = (n_pream + 4.25) * t_sym
    payload_symb_nb = 8 + max(
        math.ceil((8.0 * cfg.payload_bytes - 4.0 * sf + 28 + 16) / (4.0 * (sf - 2 * de)))
        * (cfg.coding_rate + 4),
        0,
    )
    return t_pream + payload_symb_nb * t_sym


def path_loss_db(cfg: SimConfig, distance_m: float) -> float:
    """Clamped at the fit's validity floor, NOT at d0: the reference distance is
    a parameterisation choice, whereas the validity floor is a property of the
    field data the model was fitted to."""
    d = max(distance_m, cfg.min_valid_distance_m)
    return cfg.path_loss_ref_db + 10 * cfg.path_loss_exponent * math.log10(
        d / cfg.path_loss_ref_distance_m
    )


def rssi_dbm(cfg: SimConfig, distance_m: float) -> float:
    return cfg.tx_power_dbm + cfg.net_antenna_gain_db - path_loss_db(cfg, distance_m)


def max_distance_m(cfg: SimConfig, min_sensitivity_dbm: float) -> float:
    """Distance at which RSSI equals the given sensitivity. Uses the same base-10
    form as `path_loss_db` (the original loraDir.py inverts in base e, which is
    inconsistent with how it computes path loss)."""
    lpl_max = cfg.tx_power_dbm + cfg.net_antenna_gain_db - min_sensitivity_dbm
    return cfg.path_loss_ref_distance_m * 10 ** (
        (lpl_max - cfg.path_loss_ref_db) / (10 * cfg.path_loss_exponent)
    )


def preamble_critical_ms(cfg: SimConfig, sf: int, n_pream: int = 8) -> float:
    """Length of the arriving packet's critical preamble section. Follows
    loraDir.py's timingCollision(): a packet may lose at most (Npream - 5)
    preamble symbols and still be acquired."""
    t_sym = (2.0 ** sf) / cfg.bw_khz
    return t_sym * (n_pream - 5)


def timing_collision(cfg: SimConfig, new_pkt, other) -> bool:
    """True when the new packet's critical preamble section overlaps an in-flight
    packet. False means it arrived late enough to be saved by the preamble, and
    no collision is registered for either packet."""
    return new_pkt.start + preamble_critical_ms(cfg, new_pkt.sf) < other.start + other.dur


def choose_sf_adaptive(
    cfg: SimConfig, distance_m: float, sf_options: Sequence[int]
) -> Optional[Tuple[int, float]]:
    """Lowest-airtime SF among `sf_options` whose sensitivity is still met at this
    distance. Returns (sf, airtime_ms), or None if no SF reaches the node."""
    prx = rssi_dbm(cfg, distance_m)
    best = None
    for sf in sf_options:
        if prx >= cfg.sensitivity_dbm[sf]:
            at = airtime_ms(cfg, sf)
            if best is None or at < best[1]:
                best = (sf, at)
    return best


# ---------------------------------------------------------------------------
# Geometry (no third-party dependency, so the engine stays install-free)
# ---------------------------------------------------------------------------

def point_in_ring(x: float, y: float, ring: Sequence[Tuple[float, float]]) -> bool:
    """Ray-casting point-in-polygon test."""
    inside = False
    n = len(ring)
    j = n - 1
    for i in range(n):
        xi, yi = ring[i]
        xj, yj = ring[j]
        if ((yi > y) != (yj > y)) and (x < (xj - xi) * (y - yi) / (yj - yi) + xi):
            inside = not inside
        j = i
    return inside


def point_in_polygons(x, y, polygons) -> bool:
    return any(point_in_ring(x, y, ring) for ring in polygons)


def polygons_bounds(polygons):
    xs = [p[0] for ring in polygons for p in ring]
    ys = [p[1] for ring in polygons for p in ring]
    return min(xs), min(ys), max(xs), max(ys)


def polygons_area_m2(polygons) -> float:
    """Sum of shoelace areas. Assumes the polygons do not overlap. The KML
    converter in tools/ checks for overlaps and warns."""
    total = 0.0
    for ring in polygons:
        s = 0.0
        n = len(ring)
        for i in range(n):
            x1, y1 = ring[i]
            x2, y2 = ring[(i + 1) % n]
            s += x1 * y2 - x2 * y1
        total += abs(s) / 2.0
    return total


def polygons_max_radius_m(polygons) -> float:
    """Distance from the gateway (origin) to the farthest vertex."""
    return max(math.hypot(x, y) for ring in polygons for (x, y) in ring)


def _sample_positions(cfg: SimConfig, n_nodes: int, max_d: float, rng: random.Random):
    """Returns [(node_id, distance_to_gateway_m), ...]."""
    if cfg.placement == "disc":
        return [(i, max_d * math.sqrt(rng.random())) for i in range(n_nodes)]

    if cfg.placement != "polygon":
        raise ValueError(f"unknown placement {cfg.placement!r}; use 'disc' or 'polygon'")
    if not cfg.placement_polygons_m:
        raise ValueError("placement='polygon' requires placement_polygons_m")

    minx, miny, maxx, maxy = polygons_bounds(cfg.placement_polygons_m)
    out = []
    guard = 0
    limit = 1000 * max(n_nodes, 1) + 10000
    while len(out) < n_nodes:
        x = rng.uniform(minx, maxx)
        y = rng.uniform(miny, maxy)
        guard += 1
        if guard > limit:
            raise RuntimeError(
                "rejection sampling failed to place all nodes. The polygon may be "
                "degenerate or vanishingly small relative to its bounding box."
            )
        if point_in_polygons(x, y, cfg.placement_polygons_m):
            out.append((len(out), math.hypot(x, y)))
    return out


# ---------------------------------------------------------------------------
# Simulation
# ---------------------------------------------------------------------------

class _Packet:
    __slots__ = ("nodeid", "sf", "channel", "rssi", "start", "dur",
                 "collided", "capacity_dropped")

    def __init__(self, nodeid, sf, channel, rssi, start, dur):
        self.nodeid = nodeid
        self.sf = sf
        self.channel = channel
        self.rssi = rssi
        self.start = start
        self.dur = dur
        self.collided = False
        self.capacity_dropped = False


def parse_scenario(scenario: str, cfg: SimConfig):
    """'SF9' -> (9, (9,)). 'MULTI' -> (None, allowed adaptive SFs)."""
    if scenario.upper() == "MULTI":
        opts = cfg.adaptive_sf_options or tuple(sorted(cfg.sensitivity_dbm))
        missing = [sf for sf in opts if sf not in cfg.sensitivity_dbm]
        if missing:
            raise ValueError(
                f"adaptive scenario allows SF{missing}, absent from sensitivity_dbm"
            )
        return None, tuple(sorted(opts))
    try:
        sf = int(scenario.upper().replace("SF", ""))
    except ValueError:
        raise ValueError(
            f"unrecognised scenario {scenario!r}. Use 'SF<n>' (e.g. 'SF9') or 'MULTI'."
        )
    if sf not in cfg.sensitivity_dbm:
        raise ValueError(
            f"scenario {scenario} needs sensitivity_dbm[{sf}], which this study "
            f"does not define. Defined: {sorted(cfg.sensitivity_dbm)}"
        )
    return sf, (sf,)


def run_single_sim(cfg: SimConfig, n_nodes: int, sim_time_ms: float,
                   scenario: str, rng: random.Random) -> dict:
    """One simulation run. `scenario` is 'SF<n>' for a fixed spreading factor or
    'MULTI' for adaptive selection by distance."""
    fixed_sf, sf_options = parse_scenario(scenario, cfg)
    max_d = max_distance_m(cfg, min(cfg.sensitivity_dbm[sf] for sf in sf_options))

    positions = _sample_positions(cfg, n_nodes, max_d, rng)

    node_sf = {}
    unreachable = 0
    for nid, d in positions:
        if fixed_sf is None:
            choice = choose_sf_adaptive(cfg, d, sf_options)
            if choice is None:
                unreachable += 1
                node_sf[nid] = None
                continue
            node_sf[nid] = choice[0]
        else:
            node_sf[nid] = fixed_sf
    node_dist = dict(positions)

    # Poisson traffic per node (exponential inter-arrival times)
    events = []
    for nid, _ in positions:
        if node_sf[nid] is None:
            continue
        t = rng.expovariate(1.0 / cfg.avg_send_interval_ms)
        while t < sim_time_ms:
            events.append((t, nid))
            t += rng.expovariate(1.0 / cfg.avg_send_interval_ms)
    events.sort(key=lambda e: e[0])

    n_transmitted = len(events)
    n_lost_signal = 0
    n_lost_capacity = 0
    collided_ids = set()

    active_by_channel_sf: Dict[tuple, list] = {}
    active_global: list = []

    for start, nid in events:
        sf = node_sf[nid]
        rssi = rssi_dbm(cfg, node_dist[nid])
        if rssi < cfg.sensitivity_dbm[sf]:
            n_lost_signal += 1
            continue

        channel = rng.randrange(cfg.n_channels)
        dur = airtime_ms(cfg, sf)
        key = (channel, sf)
        if key in active_by_channel_sf:
            active_by_channel_sf[key] = [
                p for p in active_by_channel_sf[key] if p.start + p.dur > start
            ]
        pkt = _Packet(nid, sf, channel, rssi, start, dur)

        # Chip-wide simultaneous-demodulation limit. A packet arriving when every
        # demodulation path is busy is not decoded, but its RF energy is still on
        # the air, so it must remain able to corrupt overlapping transmissions.
        if cfg.max_simultaneous_demodulations is not None:
            active_global[:] = [p for p in active_global if p.start + p.dur > start]
            if len(active_global) >= cfg.max_simultaneous_demodulations:
                pkt.capacity_dropped = True
                n_lost_capacity += 1

        for other in active_by_channel_sf.get(key, []):
            # Same channel and SF is already established by the index key.
            if not timing_collision(cfg, pkt, other):
                continue
            if abs(pkt.rssi - other.rssi) < cfg.capture_threshold_db:
                pkt.collided = True
                other.collided = True
                collided_ids.add((other.nodeid, other.start))
            elif pkt.rssi < other.rssi:
                pkt.collided = True
            else:
                other.collided = True
                collided_ids.add((other.nodeid, other.start))

        active_by_channel_sf.setdefault(key, []).append(pkt)
        if cfg.max_simultaneous_demodulations is not None and not pkt.capacity_dropped:
            active_global.append(pkt)
        # A capacity-dropped packet counts once, as a capacity loss, never also
        # as a collision.
        if pkt.collided and not pkt.capacity_dropped:
            collided_ids.add((pkt.nodeid, pkt.start))

    n_collided = len(collided_ids)
    n_received = n_transmitted - n_lost_signal - n_lost_capacity - n_collided
    der = n_received / n_transmitted if n_transmitted else float("nan")
    # DER counting only collision and weak-signal losses, which is the definition
    # used in most of the LoRa scalability literature. Reported alongside `der`
    # for comparability. The two coincide whenever the demodulation limit is not
    # binding, which is usually the case below saturation.
    der_classic = (
        (n_transmitted - n_lost_signal - n_collided) / n_transmitted
        if n_transmitted else float("nan")
    )

    return {
        "n_nodes": n_nodes,
        "scenario": scenario,
        "transmitted": n_transmitted,
        "lost_signal": n_lost_signal,
        "lost_capacity": n_lost_capacity,
        "collided": n_collided,
        "received": n_received,
        "der": der,
        "der_classic": der_classic,
        "unreachable_nodes": unreachable,
        "max_dist_m": max_d,
    }


def run_batch(cfg: SimConfig, n_nodes: int, sim_time_ms: float, scenario: str,
              n_runs: int, base_seed: int) -> dict:
    """`n_runs` independent repetitions with distinct seeds. Returns the mean and
    sample standard deviation of the DER, supporting counts, and the per-run DER
    values so a confidence interval can later be placed on the derived capacity."""
    results = [
        run_single_sim(cfg, n_nodes, sim_time_ms, scenario,
                       random.Random(base_seed * 100_000 + i))
        for i in range(n_runs)
    ]
    ders = [r["der"] for r in results]
    return {
        "scenario": scenario,
        "n_nodes": n_nodes,
        "n_runs": n_runs,
        "der_mean": stats.mean(ders),
        "der_std": stats.stdev(ders) if len(ders) > 1 else 0.0,
        "der_classic_mean": stats.mean(r["der_classic"] for r in results),
        "transmitted_mean": stats.mean(r["transmitted"] for r in results),
        "collided_mean": stats.mean(r["collided"] for r in results),
        "lost_signal_mean": stats.mean(r["lost_signal"] for r in results),
        "lost_capacity_mean": stats.mean(r["lost_capacity"] for r in results),
        "unreachable_mean": stats.mean(r["unreachable_nodes"] for r in results),
        "max_dist_m": results[0]["max_dist_m"],
        "der_runs": ders,
    }
