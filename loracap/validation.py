"""
Validation against theory.
==========================

The analytical reference for an unslotted, single-channel, single-SF LoRa
network is pure ALOHA:

    DER = exp(-2 * G),    G = N * T * lambda

with N nodes, T the time on air of one packet and lambda the per-node
transmission rate. It is a LOWER bound, not a target. A simulator that
reproduced it exactly would be a simulator that had thrown away everything
LoRa does beyond ALOHA.

So the validation is not agreement, it is DEGENERACY: switch off, one at a
time, each mechanism the analytical model does not have, and check that the
engine walks down onto the bound. Five rungs, in the order `LADDER` below
removes each mechanism, with the direction DER must move on arriving there:

    full model            as the study configures it
    no demod limit        up:   the bound assumes an unlimited receiver
    single channel        down: the bound assumes one frequency
    no capture effect     down: the bound assumes any overlap destroys both
    no preamble allowance down: the bound has no notion of a late arrival
                                surviving
    ---------------------------------------------------------------
    pure ALOHA            the analytical value

The ladder is NOT monotonic. Three of the four mechanisms help, so removing
them lowers DER. The demodulator limit is a constraint, so removing it raises
DER. Each step is therefore checked against its own declared direction, and
the last rung must land on the bound within Monte-Carlo noise. Both are
checked here rather than asserted.

What the ladder also gives you, for free, is the size of each mechanism's
contribution: the gap between two rungs is what that mechanism is worth in
this deployment. The worked example's figures are regenerated by
`python3 run.py reproduce iot4cows --only validation` and quoted in the
README, not here, so that they cannot go stale in a docstring.

A study using the lock receiver rule (`core.resolve_overlap`) gets one more
rung at the top, "lorasim rule", which swaps the rule back. From there the
ladder is exactly the LoRaSim study's ladder, so the descent onto exp(-2G)
still validates everything below it. That rung declares no direction. The
lock rule saves the first of two equal-power packets and loses both when the
later one is stronger, so which way DER moves when it is removed depends on
the deployment, and the gap is reported as what the rule is worth rather
than checked against a sign.

The lock rule also has an analytical case of its own. On one channel with no
capture and no preamble allowance, a packet survives exactly when no other is
already in the air as it starts, which with Poisson arrivals is exp(-G), half
ALOHA's vulnerable period. `run_ladder` evaluates that configuration
alongside the ladder for a lock study, and `assess` requires it to land.

The rungs are built with `dataclasses.replace`, so nothing here mutates the
study. `SimConfig.preamble_capture` is the one field that exists only for this
module, and it is documented as a validation knob in `core.py`.
"""
from __future__ import annotations

import dataclasses
import json
import math
import os
import statistics as stats
from typing import Dict, List, Optional, Sequence

from .core import SimConfig, airtime_ms, parse_scenario, run_batch

# Rungs of the ladder, in the order a mechanism is removed. Each entry's
# overrides apply CUMULATIVELY to the ones before it, and `direction` says
# which way DER must move on the step that arrives at that rung.
#
# Three of the four mechanisms the bound lacks are ones that HELP us, so
# removing them lowers DER. The demodulator limit is the exception: it is a
# constraint the bound also lacks, but it hurts, so removing it RAISES DER.
# Treating the whole ladder as monotonically decreasing would be wrong, and it
# would only look right in configurations where the limit never binds. It is
# removed first, while the full channel set is still active, because that is
# the only arrangement in which its real cost to this deployment is visible.
LADDER = [
    ("full model", {}, None),
    ("no demod limit", {"max_simultaneous_demodulations": None}, "up"),
    ("single channel", {"n_channels": 1}, "down"),
    ("no capture", {"capture_threshold_db": math.inf}, "down"),
    ("no preamble", {"preamble_capture": False}, "down"),
]

# Prepended for a study on the lock rule. "either" is a declared absence of
# direction, distinct from None, which old saved ladders use for the first
# rung and which `assess` reads as "down" for files written before rungs
# carried a direction at all.
LOCK_RUNG = ("lorasim rule", {"receiver_model": "lorasim"}, "either")


def ladder_for(cfg: SimConfig):
    """The rungs for this configuration's receiver rule."""
    if cfg.receiver_model == "lock":
        return [LADDER[0], LOCK_RUNG] + LADDER[1:]
    return list(LADDER)


def lock_bound_config(cfg: SimConfig) -> SimConfig:
    """The lock rule reduced to a first-come receiver: one channel, no
    demodulator limit, no capture, no preamble allowance, and none of the
    optional refinements."""
    return dataclasses.replace(
        cfg, receiver_model="lock", n_channels=1,
        max_simultaneous_demodulations=None, capture_threshold_db=math.inf,
        preamble_capture=False,
        # Both refinements can lose the locked packet or rescue the later
        # one, either of which would leave first-come behaviour behind.
        lock_survival_db=None, header_recapture=False,
        # Packets on other spreading factors are not in the bound either.
        inter_sf_rejection_db=None)


def lock_bound_der(cfg: SimConfig, n_nodes: int, sf: int) -> float:
    """exp(-G) on one channel: the probability that no packet is already in
    the air when one starts. Exact for Poisson arrivals and a fixed airtime,
    which is what a fixed-SF scenario has."""
    return math.exp(-offered_load(cfg, n_nodes, sf, n_channels=1))


def scenario_sf(scenario: str, cfg: SimConfig) -> int:
    """The single spreading factor a scenario fixes.

    The bound is defined for one spreading factor. An adaptive scenario
    spreads nodes over several, so there is no single T to put in the formula
    and the comparison would be meaningless rather than merely approximate."""
    fixed_sf, _ = parse_scenario(scenario, cfg)
    if fixed_sf is None:
        raise ValueError(
            f"scenario {scenario!r} selects the spreading factor adaptively, so "
            f"there is no single time on air to compare against the ALOHA bound. "
            f"Validate against a fixed-SF scenario such as 'SF8'."
        )
    return fixed_sf


def offered_load(cfg: SimConfig, n_nodes: int, sf: int,
                 n_channels: Optional[int] = None) -> float:
    """Normalised offered load G, in packets per packet-duration.

    With more than one channel the traffic divides across them, so G per
    channel falls accordingly. Pass n_channels=1 for the classic form."""
    c = cfg.n_channels if n_channels is None else n_channels
    if c < 1:
        raise ValueError("n_channels must be at least 1.")
    return (n_nodes / c) * airtime_ms(cfg, sf) / cfg.avg_send_interval_ms


def aloha_der(cfg: SimConfig, n_nodes: int, sf: int,
              n_channels: Optional[int] = None) -> float:
    """Pure-ALOHA success probability, exp(-2G).

    Bor et al., 'Do LoRa Low-Power Wide-Area Networks Scale?', MSWiM 2016,
    equation 12. The vulnerable period is two packet durations, because a
    packet is destroyed by anything starting in the interval from one duration
    before it to one duration after."""
    return math.exp(-2.0 * offered_load(cfg, n_nodes, sf, n_channels))


def aloha_throughput(g: float) -> float:
    """Normalised throughput S = G * exp(-2G), the canonical ALOHA curve.

    Peaks at G = 0.5 with S = 1/(2e), about 0.184. Included so results can be
    plotted on the axes the medium-access literature has used since 1970."""
    return g * math.exp(-2.0 * g)


def run_ladder(
    cfg: SimConfig,
    scenario: str,
    node_counts: Sequence[int],
    sim_time_s: float,
    n_runs: int,
    base_seed: int = 99,
    rungs: Optional[Sequence] = None,
    progress=None,
) -> dict:
    """Walk the degeneracy ladder across `node_counts`.

    Returns every rung's DER with its standard error, the analytical value,
    and the offered load, so the caller can both judge the result and plot it.
    `rungs` defaults to `ladder_for(cfg)`. A lock study's rows also carry
    `lock_bound`, the first-come configuration against exp(-G).
    """
    if rungs is None:
        rungs = ladder_for(cfg)
    lock = cfg.receiver_model == "lock"
    sf = scenario_sf(scenario, cfg)
    sim_time_ms = sim_time_s * 1000.0

    configs, overrides = [], {}
    for label, delta, _direction in rungs:
        overrides = {**overrides, **delta}
        configs.append((label, dataclasses.replace(cfg, **overrides)))

    rows: List[dict] = []
    total = len(node_counts) * (len(configs) + (1 if lock else 0))
    done = 0
    for n in node_counts:
        row = {
            "n_nodes": n,
            # The bound is single-channel by construction, and the final rung
            # it is compared against has been forced to one channel too.
            "offered_load": offered_load(cfg, n, sf, n_channels=1),
            "aloha_der": aloha_der(cfg, n, sf, n_channels=1),
            "rungs": {},
        }
        for label, c in configs:
            r = run_batch(c, n, sim_time_ms, scenario, n_runs, base_seed)
            sem = r["der_std"] / math.sqrt(n_runs) if n_runs > 1 else float("nan")
            row["rungs"][label] = {
                "der_mean": r["der_mean"], "der_std": r["der_std"],
                "der_sem": sem, "der_runs": r["der_runs"],
            }
            done += 1
            if progress:
                progress(done, total, n, label, r["der_mean"])
        if lock:
            r = run_batch(lock_bound_config(cfg), n, sim_time_ms, scenario,
                          n_runs, base_seed)
            row["lock_bound"] = {
                "der_mean": r["der_mean"], "der_std": r["der_std"],
                "der_sem": (r["der_std"] / math.sqrt(n_runs)
                            if n_runs > 1 else float("nan")),
                "der_runs": r["der_runs"],
                "bound": lock_bound_der(cfg, n, sf),
            }
            done += 1
            if progress:
                progress(done, total, n, "first-come", r["der_mean"])
        rows.append(row)

    return {
        "scenario": scenario,
        "spreading_factor": sf,
        "airtime_ms": airtime_ms(cfg, sf),
        "send_interval_ms": cfg.avg_send_interval_ms,
        "n_runs": n_runs,
        "sim_time_s": sim_time_s,
        "base_seed": base_seed,
        "rung_labels": [label for label, _, _ in rungs],
        "rung_directions": [direction for _, _, direction in rungs],
        "rows": rows,
        "reference": (
            "Bor, Roedig, Voigt and Alonso, 'Do LoRa Low-Power Wide-Area "
            "Networks Scale?', MSWiM 2016, eq. 12 (updated version)"
        ),
    }


def assess(ladder: dict, sigmas: float = 3.0) -> dict:
    """Judge a ladder: does each step move the way it must, and does the last
    rung land on the bound?

    Each step is checked against its own declared direction rather than
    against a blanket assumption that DER only falls, because removing the
    demodulator limit relaxes a constraint and so moves DER the other way.

    The agreement test is in units of the simulation's own standard error
    rather than a fixed percentage, because at high load the DER is small and
    a 2% relative gap can be pure noise while at low load it would not be."""
    labels = ladder["rung_labels"]
    directions = ladder.get("rung_directions") or [None] + ["down"] * (len(labels) - 1)
    last = labels[-1]

    violations = []
    for row in ladder["rows"]:
        vals = [row["rungs"][l]["der_mean"] for l in labels]
        sems = [row["rungs"][l]["der_sem"] for l in labels]
        for i in range(len(vals) - 1):
            if directions[i + 1] == "either":
                continue
            # Allow the combined noise of the two estimates before calling a
            # step a breach of its declared direction.
            tol = sigmas * math.hypot(
                0.0 if math.isnan(sems[i]) else sems[i],
                0.0 if math.isnan(sems[i + 1]) else sems[i + 1],
            )
            delta = vals[i + 1] - vals[i]
            want = directions[i + 1] or "down"
            breached = (delta > tol) if want == "down" else (-delta > tol)
            if breached:
                violations.append({
                    "n_nodes": row["n_nodes"], "from": labels[i], "to": labels[i + 1],
                    "expected": want, "delta": delta, "tolerance": tol,
                })

    agreement = []
    for row in ladder["rows"]:
        d = row["rungs"][last]["der_mean"]
        sem = row["rungs"][last]["der_sem"]
        a = row["aloha_der"]
        z = (d - a) / sem if sem and not math.isnan(sem) and sem > 0 else float("nan")
        agreement.append({
            "n_nodes": row["n_nodes"], "degenerate": d, "aloha": a,
            "abs_gap": d - a,
            "rel_gap": (d - a) / a if a > 0 else float("nan"),
            "z": z,
        })

    agree_ok = [x for x in agreement if math.isnan(x["z"]) or abs(x["z"]) <= sigmas]
    verdict = {
        "directions_hold": not violations,
        "violations": violations,
        "agreement": agreement,
        "n_agree": len(agree_ok),
        "n_points": len(agreement),
        "sigmas": sigmas,
        "passes": not violations and len(agree_ok) == len(agreement),
    }
    # Only a lock study has these rows, and a LoRaSim study's verdict keeps
    # exactly the keys it always had, so its saved file does not change.
    if any("lock_bound" in row for row in ladder["rows"]):
        lock_agree = []
        for row in ladder["rows"]:
            lb = row["lock_bound"]
            sem, d, a = lb["der_sem"], lb["der_mean"], lb["bound"]
            z = (d - a) / sem if sem and not math.isnan(sem) and sem > 0 else float("nan")
            lock_agree.append({"n_nodes": row["n_nodes"], "first_come": d,
                               "bound": a, "abs_gap": d - a, "z": z})
        lock_ok = [x for x in lock_agree
                   if math.isnan(x["z"]) or abs(x["z"]) <= sigmas]
        verdict["lock_agreement"] = lock_agree
        verdict["n_lock_agree"] = len(lock_ok)
        verdict["passes"] = verdict["passes"] and len(lock_ok) == len(lock_agree)
    return verdict


def contributions(ladder: dict, n_nodes: Optional[int] = None) -> List[dict]:
    """What each mechanism is worth, in DER, at one node count.

    Read upwards: the gap between a rung and the one below it is what the
    mechanism removed at that step contributes in this deployment."""
    row = (ladder["rows"][-1] if n_nodes is None
           else next(r for r in ladder["rows"] if r["n_nodes"] == n_nodes))
    labels = ladder["rung_labels"]
    directions = ladder.get("rung_directions") or [None] + ["down"] * (len(labels) - 1)
    # The name of the mechanism, as opposed to the name of the rung reached by
    # removing it.
    names = {
        "no demod limit": "demodulator limit",
        "single channel": "multiple channels",
        "no capture": "capture effect",
        "no preamble": "preamble allowance",
        "lorasim rule": "receiver lock",
    }
    out = []
    for i in range(len(labels) - 1):
        above = row["rungs"][labels[i]]["der_mean"]
        below = row["rungs"][labels[i + 1]]["der_mean"]
        out.append({
            "mechanism": names.get(labels[i + 1], labels[i + 1]),
            "removed_at": labels[i + 1],
            "direction": directions[i + 1] or "down",
            "der_above": above, "der_below": below,
            # Positive means the mechanism raises DER in this deployment,
            # negative means it costs DER.
            "worth": above - below,
        })
    return {"n_nodes": row["n_nodes"], "steps": out,
            "aloha": row["aloha_der"],
            "residual": row["rungs"][labels[-1]]["der_mean"] - row["aloha_der"]}


def format_ladder(ladder: dict, verdict: Optional[dict] = None) -> str:
    """The ladder as a table, plus what it means."""
    if verdict is None:
        verdict = assess(ladder)
    labels = ladder["rung_labels"]
    L = []
    L.append(f"Degeneracy ladder towards the pure-ALOHA bound")
    L.append(f"  scenario {ladder['scenario']}, {ladder['n_runs']} runs per point, "
             f"{ladder['sim_time_s']:.0f} s simulated")
    L.append(f"  SF{ladder['spreading_factor']} airtime {ladder['airtime_ms']:.1f} ms, "
             f"mean interval {ladder['send_interval_ms'] / 1000:.0f} s")
    L.append("")

    w = max(len(l) for l in labels) + 3
    head = f"{'N':>6}{'G':>8}" + "".join(f"{l:>{w}}" for l in labels) + f"{'ALOHA':>10}"
    L.append(head)
    L.append("  " + "-" * (len(head) - 2))
    for row in ladder["rows"]:
        line = f"{row['n_nodes']:>6}{row['offered_load']:>8.3f}"
        for l in labels:
            line += f"{row['rungs'][l]['der_mean']:>{w}.4f}"
        line += f"{row['aloha_der']:>10.4f}"
        L.append(line)

    L.append("")
    L.append("  Verdict")
    if verdict["directions_hold"]:
        L.append("    Every step moves the way it must: removing a mechanism that")
        L.append("    helps lowers DER, and removing the demodulator limit, which")
        L.append("    is a constraint rather than a help, raises it.")
    else:
        L.append(f"    WRONG DIRECTION at {len(verdict['violations'])} step(s).")
        for v in verdict["violations"][:4]:
            L.append(f"      N={v['n_nodes']}: {v['from']} -> {v['to']} moved "
                     f"{v['delta']:+.4f}, expected {v['expected']} "
                     f"(tolerance {v['tolerance']:.4f})")

    n_ok, n_all = verdict["n_agree"], verdict["n_points"]
    worst = max(verdict["agreement"],
                key=lambda a: abs(a["z"]) if not math.isnan(a["z"]) else -1)
    if n_ok == n_all:
        L.append(f"    Lands on the bound: all {n_all} points agree with exp(-2G)")
        L.append(f"    within {verdict['sigmas']:.0f} standard errors. Largest "
                 f"deviation {worst['rel_gap'] * 100:+.1f}% at N={worst['n_nodes']}.")
        L.append("    The engine reduces to the analytical case when the mechanisms")
        L.append("    it adds are switched off, which is what validates it. It is")
        L.append("    not supposed to match the bound with them switched on.")
    else:
        L.append(f"    DOES NOT land on the bound: {n_all - n_ok} of {n_all} points")
        L.append(f"    differ from exp(-2G) by more than {verdict['sigmas']:.0f} "
                 f"standard errors.")
        L.append(f"    Worst: N={worst['n_nodes']}, {worst['degenerate']:.4f} against "
                 f"{worst['aloha']:.4f} ({worst['rel_gap'] * 100:+.1f}%).")
        L.append("    Either a mechanism is still active that should not be, or the")
        L.append("    run count is too low for this comparison to mean anything.")

    if "lock_agreement" in verdict:
        L.append("")
        L.append("  The lock rule's own bound: one channel, no capture, no preamble")
        L.append("  allowance, against exp(-G)")
        L.append(f"{'N':>8}{'first-come':>14}{'exp(-G)':>11}{'z':>8}")
        for a in verdict["lock_agreement"]:
            L.append(f"{a['n_nodes']:>8}{a['first_come']:>14.4f}"
                     f"{a['bound']:>11.4f}{a['z']:>8.2f}")
        n_ok, n_all = verdict["n_lock_agree"], len(verdict["lock_agreement"])
        if n_ok == n_all:
            L.append(f"    Lands on exp(-G): all {n_all} points within "
                     f"{verdict['sigmas']:.0f} standard errors.")
        else:
            L.append(f"    DOES NOT land on exp(-G): {n_all - n_ok} of {n_all} "
                     f"points outside {verdict['sigmas']:.0f} standard errors.")

    c = contributions(ladder)
    L.append("")
    L.append(f"  What each mechanism is worth at N = {c['n_nodes']}")
    L.append("    Positive means it raises DER in this deployment, negative that")
    L.append("    it costs DER.")
    for s in c["steps"]:
        note = "   no direction required" if s["direction"] == "either" else ""
        L.append(f"    {s['mechanism']:<22} {s['worth']:+.4f} DER   "
                 f"({s['der_above']:.4f} -> {s['der_below']:.4f}){note}")
    L.append(f"    {'residual vs ALOHA':<22} {c['residual']:+.4f} DER")
    return "\n".join(L)


def write_ladder(study_name: str, ladder: dict, verdict: Optional[dict] = None,
                 root=None, out_dir=None, provenance=None) -> str:
    from .study import output_dir
    if verdict is None:
        verdict = assess(ladder)
    out = out_dir or output_dir(study_name, root)
    os.makedirs(out, exist_ok=True)
    payload = {"ladder": ladder, "verdict": verdict}
    if provenance is not None:
        payload["provenance"] = provenance
    path = os.path.join(out, "validation.json")
    with open(path, "w") as f:
        json.dump(payload, f, indent=2)
    return path
