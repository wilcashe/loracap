#!/usr/bin/env python3
"""
Reproduction of Bor et al.'s Experiment Set 1, configuration SN3.
=================================================================

Source
------
Bor, Roedig, Voigt and Alonso, "Do LoRa Low-Power Wide-Area Networks Scale?",
MSWiM 2016. Use the UPDATED version: Mariusz Slabicki found a bug by which
already-collided packets were in some cases marked as not collided, which
overestimated goodput. The figures were corrected and the conclusions held.

Published result: with the default LoRaWAN configuration SN3 and a DER > 0.9
requirement, N = 64 nodes can be supported.

WHAT THIS REPRODUCTION FOUND
----------------------------
The engine does not reach the paper's figure, and the paper disagrees with
itself.

  this study (LoRaCAP)           51.4 nodes, 95% CI [49.8, 52.4]
  paper, abstract/body/findings  64 nodes
  paper, Figure 4 caption        120 nodes

The LoRaCAP row is regenerated by `python3 run.py reproduce bor2016_sn3
--only headline`. Airtime for SN1 matches the published 1712.13 ms exactly
(see bor2016_sn1). SN3's coding rate of 4/5 gives 1318.91 ms.

The paper is internally inconsistent: 64 appears in the abstract, the body
and the findings, while Figure 4's caption says 120 for the same
configuration. That is the signature of text and figures drifting apart,
which fits the footnote recording that every figure was regenerated after
Mariusz Slabicki found a bug that overestimated goodput.

During development LoRaSim itself (github.com/mcbor/lorasim, converted to
Python 3) was run at these settings outside this repository. Its capacity
came out close to this engine's, not near 64, the capacity the paper states
for SN3 in its abstract, body and findings. That run is not part of the
repository and cannot be regenerated from it, so it is context, not
evidence, and none of its figures are quoted (design item 30).

Two things this cannot settle. LoRaSim's repository is a single commit from
2021 with no history, so whether it holds the corrected code cannot be
established from it. And the bug overestimated goodput, so if that code is
still the buggy version, a corrected simulation would support fewer nodes
still, further from 64, not closer.

Treat 64 as unverified.

Why this study exists
---------------------
The degeneracy ladder in `run.py validate` checks the engine against ALOHA
theory. This sets up the configuration of an independent published
simulation and compares with what its paper reports, which is a different
question: theory says what the floor is, Bor et al. say what their simulator
got for a specific configuration. After any substantial change to the engine
it is the thing to re-run.

Every value below is from the paper, not inferred. Table 2 gives the
transmitter settings, Section 3.2 gives the propagation model, Table 1 gives
the measured receiver sensitivity.

Three settings that are NOT this tool's defaults, and would quietly produce a
different number if left alone:

  * ONE channel. SN3 fixes CF at 868 MHz. This tool defaults to the gateway
    chip's channel count, which would be eight.
  * NO demodulator limit. LoRaSim does not model an SX1301 concentrator.
  * THEIR sensitivity figures, measured on an XRange SX1272, which is a node
    radio. This tool's presets are gateway concentrators, and the two are not
    interchangeable.

Note on sigma. The paper fits sigma = 3.57 dB for the shadowing term and then
sets it to zero, stating that otherwise "some transmissions might not be able
to reach the sink rendering our results inconclusive". That is worth reading
twice: the variability was removed because it broke the result. This study
keeps sigma at zero to reproduce their figure. `shadowing_sigma_db=3.57` turns
it back on, and what happens then is a question their paper does not answer.
"""
from loracap import Study

# Table 1, measured receiver sensitivity at 125 kHz [dBm]. SF12 is less
# sensitive than SF11 in their measurements, which is their result, not a
# transcription error.
SENSITIVITY_125KHZ_XRANGE_SX1272 = {
    7: -126.50, 8: -127.25, 9: -131.25,
    10: -132.75, 11: -134.50, 12: -133.25,
}

STUDY = Study(
    name="bor2016_sn3",
    site="Bor et al. 2016, Experiment Set 1, SN3 (default LoRaWAN)",
    description=(
        "Reproduction target: N = 64 nodes at DER > 0.9. "
        "Bor, Roedig, Voigt and Alonso, MSWiM 2016, updated version."
    ),

    # --- band and spreading factors ---
    region="EU868",
    bw_khz=125,
    spreading_factors=(12,),

    # --- gateway: LoRaSim models neither a concentrator nor a channel plan ---
    sensitivity_dbm=SENSITIVITY_125KHZ_XRANGE_SX1272,
    n_channels=1,
    max_simultaneous_demodulations=None,

    # --- link budget: Prx = Ptx + GL - Lpl, with GL = 0 ---
    tx_power_dbm=14.0,
    tx_antenna_gain_db=0.0,
    rx_antenna_gain_db=0.0,
    cable_loss_db=0.0,

    # --- propagation, Section 3.2: d0 = 40 m, Lpl(d0) = 127.41 dB, gamma = 2.08 ---
    path_loss_exponent=2.08,
    path_loss_ref_db=127.41,
    path_loss_ref_distance_m=40.0,
    min_valid_distance_m=1.0,
    shadowing_sigma_db=0.0,
    path_loss_source=(
        "Bor et al. 2016, Section 3.2: empirical measurements in a built-up "
        "environment, d0 = 40 m, Lpl(d0) = 127.41 dB, gamma = 2.08, "
        "sigma = 3.57 dB set to zero by the authors"
    ),

    # --- traffic, Table 2: 20 B every 16.7 min, CR 4/5 ---
    payload_bytes=20,
    # Bor et al. time a bare 20-byte LoRa payload. The airtime they publish
    # for Experiment Set 1, 1712.13 ms at SF12 and CR 4/8, is that of 20
    # bytes with nothing added (see bor2016_sn1), so the LoRaWAN header is
    # left out here too (design item 33). Adding it would lengthen this
    # set's SF12 uplink at CR 4/5 from 1318.91 ms to 1810.43 ms.
    lorawan_overhead_bytes=0,
    coding_rate=1,
    send_interval_s=1000.0,
    capture_threshold_db=6.0,

    # LoRaSim computes transmit energy for this configuration with the same
    # SX1272 current table, entry for entry, so the two are directly
    # comparable. No comparison is quoted, because the LoRaSim run that made
    # one is not in this repository (design item 30). This engine's figures
    # are experiment `energy` in experiments.py.
    radio="SX1272",
    supply_voltage_v=3.0,

    # --- placement: nodes uniformly inside the coverage disc ---
    placement="disc",

    # --- experiment design ---
    scenarios=("SF12",),
    node_counts=(10, 20, 30, 40, 50, 55, 60, 64, 70, 80, 90, 100, 120,
                 150, 200, 250, 300),
    sim_time_s=200_000.0,      # 200 packets per node
    n_runs=15,
    base_seed=99,
    der_threshold=0.9,

    highlight_scenario="SF12",
    figure_basename="bor2016_sn3",
)
